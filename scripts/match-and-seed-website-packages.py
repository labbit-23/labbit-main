"""One-time Phase 2+3 script for the website packages -> labit_core.package
matching/seeding plan (director, 2026-09-20 -- see db/migrations/
20260920_packages_website_columns.sql).

Phase 2 (name/price matching): "Match with price as a more stronger link,
words like wellness and checkup are used interchangeably." For each
public.packages row with source='json_migration', find labit_core.package
rows on the DEFAULT price list with an EXACT rate match, then break ties
(or confirm a single candidate) by content-word token overlap against the
package's group_name + variant name (noise words like
wellness/checkup/health/profile/plan stripped, since the director noted
they're used interchangeably and carry no matching signal). A single
candidate at the matched price -> matched. Zero candidates ->
no_core_equivalent. Multiple candidates with no clear token-overlap
winner -> ambiguous, left for manual review rather than guessed.

Run 2026-09-20 against the 24 migrated variants: 20 matched, 3
no_core_equivalent (confirmed by director as genuine marketing-only
add-ons: Executive Plus, Fitness & Body Composition Profile, Hair Fall
Advanced -- no code change needed, these just stay unmatched), 1
ambiguous (Women's Comprehensive, WHB "...CheckUp (BMD)" vs WHP
"...Check&Up (Mam)" both at Rs 8499 -- director: "The website has 1
either or for women, the system actually needs 2" -- resolved by
SPLITTING that one website row into two real rows, one per core package,
rather than picking one arbitrarily).

Phase 3 (composition seed): for every matched row, pulls
labit_core.package_item (test_id, display_order) for the linked core
package and writes it into public.package_items (item_type='test',
item_id=the labit_core.test.id -- no FK possible, cross-database
reference by design, same posture as core_package_id on packages
itself). Re-running this script deletes and re-inserts package_items for
every currently-matched package_id, so it's safe to re-run after a
re-match; it is NOT yet wired into any recurring Live Sync route (that's
still open -- see this file's own module docstring above).

This script is a RECORD of the one-time run, not a repeatedly-scheduled
job -- there is no cron/API route calling it. Needs both labit-core's
LABIT_PG_DSN (via an SSH tunnel to labit.sdrc.in, see
vps1-ssh-access memory) and direct psql access to the labit-main Supabase
Postgres (ssh root@supabase.sdrc.in -> docker exec supabase-db psql).
"""
import os
import re
import json

import psycopg
from psycopg.rows import dict_row

NOISE_WORDS = {
    "wellness", "checkup", "check", "up", "the", "and", "&", "of",
    "profile", "package", "plan", "health",
}


def content_tokens(name: str) -> set[str]:
    name = (name or "").lower()
    name = re.sub(r"[()/,.\-]", " ", name)
    return set(name.split()) - NOISE_WORDS


def match(core_rows: list[dict], web_rows: list[dict]) -> list[dict]:
    results = []
    for w in web_rows:
        wprice = float(w["price"]) if w["price"] is not None else None
        w_tokens = content_tokens(w["group_name"]) | content_tokens(w["name"])
        candidates = [c for c in core_rows if wprice is not None and float(c["rate"]) == wprice]
        scored = sorted(
            ((len(content_tokens(c["name"]) & w_tokens), c) for c in candidates),
            key=lambda x: -x[0],
        )

        if not candidates:
            status, chosen = "no_core_equivalent", None
        elif len(candidates) == 1:
            status, chosen = "matched", candidates[0]
        else:
            top_score = scored[0][0]
            top = [c for score, c in scored if score == top_score]
            status, chosen = ("matched", top[0]) if len(top) == 1 and top_score > 0 else ("ambiguous", None)

        results.append({
            "web_id": w["id"], "status": status,
            "chosen_id": str(chosen["id"]) if chosen else None,
            "chosen_code": chosen["code"] if chosen else None,
        })
    return results


def fetch_core_priced_packages(cur) -> list[dict]:
    cur.execute("SELECT id FROM labit_core.price_list WHERE is_default LIMIT 1")
    pl = cur.fetchone()
    cur.execute(
        "SELECT p.id, p.code, p.name, pr.rate FROM labit_core.package p "
        "JOIN labit_core.price pr ON pr.package_id = p.id "
        "WHERE pr.price_list_id = %s AND pr.branch_id IS NULL "
        "AND pr.valid @> (now() AT TIME ZONE 'Asia/Kolkata')::date AND p.active "
        "ORDER BY p.name",
        (pl["id"],),
    )
    return cur.fetchall()


def fetch_core_composition(cur, core_package_id: str) -> list[dict]:
    cur.execute(
        "SELECT t.id AS test_id, pi.display_order FROM labit_core.package_item pi "
        "JOIN labit_core.test t ON t.id = pi.test_id "
        "WHERE pi.package_id = %s ORDER BY pi.display_order",
        (core_package_id,),
    )
    return cur.fetchall()


